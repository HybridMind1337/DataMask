package transformers

import (
	"context"
	"fmt"
	"regexp"

	"github.com/HybridMind1337/DataMask/internal/masking"
)

var (
	emailScrubPattern = regexp.MustCompile(`(?i)[a-z0-9._%+\-]+@[a-z0-9.\-]+\.[a-z]{2,}`)
	phoneScrubPattern = regexp.MustCompile(`\+?[0-9]{1,3}?[-.\s]?\(?[0-9]{2,4}\)?[-.\s]?[0-9]{3,4}[-.\s]?[0-9]{3,4}`)
	jwtScrubPattern   = regexp.MustCompile(`eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9._-]{10,}`)
)

// FreeTextScrubTransformer scrubs identified sensitive patterns inside free-text columns.
type FreeTextScrubTransformer struct{}

func (t *FreeTextScrubTransformer) Name() string { return "pattern_scrub" }
func (t *FreeTextScrubTransformer) Description() string {
	return "Scans free-text content and replaces embedded emails, phones, and tokens with safe placeholders"
}
func (t *FreeTextScrubTransformer) Transform(ctx context.Context, value any, meta masking.FieldMetadata, tCtx masking.TransformContext) (any, error) {
	if value == nil {
		return nil, nil
	}
	text := fmt.Sprintf("%v", value)
	text = emailScrubPattern.ReplaceAllString(text, "[REDACTED_EMAIL]")
	text = phoneScrubPattern.ReplaceAllString(text, "[REDACTED_PHONE]")
	text = jwtScrubPattern.ReplaceAllString(text, "[REDACTED_TOKEN]")
	return text, nil
}

// SyntheticTextTransformer replaces entire free-text field with safe dummy text.
type SyntheticTextTransformer struct{}

func (t *SyntheticTextTransformer) Name() string { return "synthetic_text" }
func (t *SyntheticTextTransformer) Description() string {
	return "Replaces free text with generic safe sample notes"
}
func (t *SyntheticTextTransformer) Transform(ctx context.Context, value any, meta masking.FieldMetadata, tCtx masking.TransformContext) (any, error) {
	if value == nil {
		return nil, nil
	}
	return "Sample system text generated by DataMask for development and staging verification.", nil
}
