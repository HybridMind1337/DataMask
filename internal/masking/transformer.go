package masking

import (
	"context"
	"sync"

	"github.com/HybridMind1337/DataMask/internal/security"
)

// FieldMetadata provides schema and column context for the value being transformed.
type FieldMetadata struct {
	SchemaName      string
	TableName       string
	ColumnName      string
	DataType        string
	IsNullable      bool
	IsPrimaryKey    bool
	IsForeignKey    bool
	IsUnique        bool
	ReferencedTable string
	ReferencedCol   string
	RowIdentifier   any // Stable primary key or sequential ID for safe error tracking
}

// TransformContext exposes runtime entropy, key derivation, and collision caches.
type TransformContext interface {
	IsDeterministic() bool
	KeyDeriver() *security.KeyDeriver
	CollisionTracker() *CollisionTracker
	DevPasswordHash() string
}

// Transformer defines a single masking strategy implementation.
type Transformer interface {
	Name() string
	Description() string
	Transform(ctx context.Context, value any, meta FieldMetadata, tCtx TransformContext) (any, error)
}

// CollisionTracker guards against generating duplicate values for columns with unique constraints
// while ensuring deterministic transforms return the identical value when called with identical source values.
type CollisionTracker struct {
	mu           sync.RWMutex
	seen         map[string]map[any]bool // "table.column" -> set of generated values
	sourceToDest map[string]map[any]any  // "table.column" -> map[sourceVal]destVal
}

// NewCollisionTracker initializes a tracker.
func NewCollisionTracker() *CollisionTracker {
	return &CollisionTracker{
		seen:         make(map[string]map[any]bool),
		sourceToDest: make(map[string]map[any]any),
	}
}

// GetExisting returns a previously generated destination value for the same source input, if any.
func (c *CollisionTracker) GetExisting(table, column string, sourceVal any) (any, bool) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	key := table + "." + column
	if m, ok := c.sourceToDest[key]; ok {
		val, exists := m[sourceVal]
		return val, exists
	}
	return nil, false
}

// IsDuplicate returns true if the candidate destination value was already generated by another source row.
func (c *CollisionTracker) IsDuplicate(table, column string, destVal any) bool {
	c.mu.RLock()
	defer c.mu.RUnlock()
	key := table + "." + column
	if set, ok := c.seen[key]; ok {
		return set[destVal]
	}
	return false
}

// Record records a newly generated value mapping sourceVal -> destVal.
func (c *CollisionTracker) Record(table, column string, sourceVal, destVal any) {
	c.mu.Lock()
	defer c.mu.Unlock()
	key := table + "." + column
	if _, ok := c.seen[key]; !ok {
		c.seen[key] = make(map[any]bool)
		c.sourceToDest[key] = make(map[any]any)
	}
	c.seen[key][destVal] = true
	c.sourceToDest[key][sourceVal] = destVal
}

// DefaultTransformContext is a concrete implementation of TransformContext.
type DefaultTransformContext struct {
	deterministic   bool
	keyDeriver      *security.KeyDeriver
	tracker         *CollisionTracker
	devPasswordHash string
}

// NewTransformContext creates an initialized transformation context.
func NewTransformContext(deterministic bool, deriver *security.KeyDeriver, devHash string) *DefaultTransformContext {
	return &DefaultTransformContext{
		deterministic:   deterministic,
		keyDeriver:      deriver,
		tracker:         NewCollisionTracker(),
		devPasswordHash: devHash,
	}
}

func (d *DefaultTransformContext) IsDeterministic() bool {
	return d.deterministic
}

func (d *DefaultTransformContext) KeyDeriver() *security.KeyDeriver {
	return d.keyDeriver
}

func (d *DefaultTransformContext) CollisionTracker() *CollisionTracker {
	return d.tracker
}

func (d *DefaultTransformContext) DevPasswordHash() string {
	return d.devPasswordHash
}
